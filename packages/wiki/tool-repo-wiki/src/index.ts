/**
 * Model-facing `read_wiki` tool over `ctx.repoWiki`: read one generated wiki page
 * (optionally as its heading outline) or list the whole wiki, marking pages whose
 * sources changed after generation as stale. Returns an actionable "wiki
 * unavailable" answer — without failing the session — when no provider is mounted.
 * It runtime-injects only `tools`, `repoWiki`, and `systemPrompt` and imports no
 * provider.
 *
 * Namespace plugin (named exports, no default export).
 * @module @deepseek-ai/dsh-tool-repo-wiki
 */

import type { Context } from '@deepseek-ai/cordis'
import z from '@deepseek-ai/schemastery'
import { defineTool } from '@deepseek-ai/dsh-tools'
import { RepoWikiError } from '@deepseek-ai/dsh-repo-wiki'
import type {} from '@deepseek-ai/dsh-repo-wiki'
import { MAX_TIMER_DELAY_MS } from '@deepseek-ai/dsh-timeout'
import {
  DEFAULT_MAX_RESULT_CHARS,
  parseReadWikiArgs,
  presentReadWikiCall,
  renderValue,
} from './render.ts'

export {
  DEFAULT_MAX_RESULT_CHARS,
  formatListing,
  formatOutline,
  formatOutlineOrListing,
  formatPage,
  parseReadWikiArgs,
  presentReadWikiCall,
  renderValue,
  UNAVAILABLE_TEXT,
} from './render.ts'
export type { ReadWikiArgs, ReadWikiInput, ReadWikiResult } from './render.ts'

/** Cordis plugin name for loader diagnostics. */
export const name = 'tool-repo-wiki'

/** Services required by this plugin. */
export const inject = ['tools', 'repoWiki', 'systemPrompt']

/** Default tool-call timeout budget (ms), covering provider directory reads. */
export const DEFAULT_REPO_WIKI_TOOL_TIMEOUT_MS = 30_000

/** The stable system-prompt guidance positioning the wiki among repo-reading tools. */
export const REPO_WIKI_PROMPT_TEXT =
  'Before answering questions about this repository\'s architecture, packages, or documented behavior, check read_wiki: the repo wiki holds generated, consolidated pages (with a per-page heading outline) that are cheaper to read than re-deriving the same picture from source. Pages marked stale may be outdated — verify against the live files when precision matters. The wiki is unavailable until a repo-wiki provider is configured; then fall back to search/read.'

/** Plugin configuration: the result cap and the timeout budget. */
export interface Config {
  /** Largest complete rendered result in characters, including truncation metadata (default 16000). */
  maxResultChars?: number
  /** Tool-call timeout budget in ms (default 30000). */
  timeoutMs?: number
}

export const Config: z<Config> = z.object({
  maxResultChars: z.number().default(DEFAULT_MAX_RESULT_CHARS),
  timeoutMs: z.number().max(MAX_TIMER_DELAY_MS).default(DEFAULT_REPO_WIKI_TOOL_TIMEOUT_MS),
})

type ResolvedConfig = Required<Config>

/**
 * Register the `read_wiki` tool and its system-prompt guidance.
 * @param ctx - the plugin context (must inject `tools`, `repoWiki`, `systemPrompt`).
 * @param config - the resolved plugin configuration.
 */
export function apply(ctx: Context, config: Config): void {
  const resolved = config as ResolvedConfig
  assertPositiveInteger('maxResultChars', resolved.maxResultChars)
  assertTimer('timeoutMs', resolved.timeoutMs)

  ctx.systemPrompt.section({
    name: 'tool:repo-wiki',
    order: ctx.systemPrompt.getSectionOrder('TOOL_REPO_WIKI'),
    text: REPO_WIKI_PROMPT_TEXT,
  })

  ctx.tools.register(defineTool({
    name: 'read_wiki',
    description:
      'Read the repository wiki generated by the harness. Without arguments, lists every page (path, title, staleness). With path, returns one page\'s full Markdown content — or, with outline=true, its heading structure. Stale pages were generated from sources that have since changed. Returns an actionable unavailable message when no repo-wiki provider is configured.',
    parameters: {
      path: { type: 'string', description: 'Wiki page path to read (as listed without arguments); omit to list every page.' },
      outline: { type: 'boolean', description: 'With path, return the page\'s heading outline instead of its full content.' },
    },
    output: {
      schema: {
        type: 'object',
        additionalProperties: false,
        properties: {
          status: { type: 'string', required: true, enum: ['ok', 'unavailable'] },
          path: { type: 'string' },
          title: { type: 'string' },
          stale: { type: 'boolean' },
          content: { type: 'string' },
          pages: {
            type: 'array',
            items: {
              type: 'object',
              additionalProperties: false,
              properties: {
                path: { type: 'string', required: true },
                title: { type: 'string', required: true },
                stale: { type: 'boolean', required: true },
                headings: { type: 'array', items: { type: 'string' } },
              },
            },
          },
        },
      },
      render: (_args, value) => [
        { type: 'text', text: renderValue(value, resolved.maxResultChars) },
      ],
    },
    timeoutMs: resolved.timeoutMs,
    isConcurrencySafe: () => true,
    async execute(args) {
      const input = parseReadWikiArgs(args)
      try {
        if (input.path === undefined) {
          const listing = await ctx.repoWiki.listPages()
          return { status: 'ok' as const, pages: listing.pages.map(page => ({ path: page.path, title: page.title, stale: page.stale })) }
        }
        if (input.outline === true) {
          const entries = await ctx.repoWiki.outline()
          const entry = entries.find(candidate => candidate.path === input.path)
          if (entry === undefined) throw new RepoWikiError(`no wiki page at ${JSON.stringify(input.path)}`, 'REPO_WIKI_NOT_FOUND')
          return { status: 'ok' as const, pages: [{ path: entry.path, title: entry.title, stale: entry.stale, headings: [...entry.headings] }] }
        }
        const page = await ctx.repoWiki.getPage(input.path)
        return { status: 'ok' as const, path: page.path, title: page.title, stale: page.stale, content: page.content }
      } catch (error) {
        if (error instanceof RepoWikiError && error.code === 'REPO_WIKI_UNAVAILABLE') {
          return { status: 'unavailable' as const }
        }
        throw error
      }
    },
    presentCall: presentReadWikiCall,
  }))
}

/** Reject a non-positive-integer config value at load, so misconfiguration fails loud. */
function assertPositiveInteger(configName: string, value: number): void {
  if (!Number.isInteger(value) || value < 1) {
    throw new Error(`tool-repo-wiki: ${configName} must be a positive integer`)
  }
}

/** Reject a timer value Node would clamp instead of scheduling as configured. */
function assertTimer(configName: string, value: number): void {
  if (!Number.isInteger(value) || value < 1 || value > MAX_TIMER_DELAY_MS) {
    throw new Error(`tool-repo-wiki: ${configName} must be a positive integer no greater than ${MAX_TIMER_DELAY_MS}`)
  }
}
